#!/usr/bin/env bash
# Builds the Nextcloud app: internal WAD, bundled Freedoom, wasm engine, and
# optionally the release archive. Run from anywhere; needs emsdk on PATH.
#
#   ./nextcloud/tools/build-app.sh [--pack]
#
# Reproducibility (R9): the Dwasm commit is this checkout, emsdk is pinned
# below, and both content hashes are verified rather than trusted.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
engine="$root/nextcloud/engine"
native="$root/build-native"
build="$root/build"

emsdk_version="3.1.74"
prboom_wad_sha="506fe7159eaf0a6cb479f866131ec7653638bb08928029cb8dabe1b3b1c9474d"
freedoom_version="0.13.0"
freedoom_zip_sha="3f9b264f3e3ce503b4fb7f6bdcb1f419d93c7b546f4df3e874dd878db9688f59"

sha() { sha256sum "$1" 2>/dev/null | cut -d' ' -f1; }

command -v emcc >/dev/null || {
	echo "error: emcc not found; install emsdk $emsdk_version and source emsdk_env.sh" >&2
	exit 1
}
echo "Building with $(emcc --version | head -1)"

# 1. The internal WAD is generated by a native build of the same tree, and its
#    hash is pinned in README.md: a mismatch means the tree changed under us.
if [[ "$(sha "$root/wasm/fs/prboomx.wad")" != "$prboom_wad_sha" ]]; then
	cmake -S "$root" -B "$native" -DCMAKE_BUILD_TYPE=Release
	cmake --build "$native" --target prboomwad -j"$(nproc)"
	cp "$native/prboomx.wad" "$root/wasm/fs/prboomx.wad"
fi
if [[ "$(sha "$root/wasm/fs/prboomx.wad")" != "$prboom_wad_sha" ]]; then
	echo "error: wasm/fs/prboomx.wad does not match the pinned SHA-256" >&2
	exit 1
fi

# 2. Freedoom: free licence, downloaded once, hash-verified, stored gzip -n
#    (no timestamp, so the archive is byte-reproducible).
cache="${XDG_CACHE_HOME:-$HOME/.cache}/dwasm"
zip="$cache/freedoom-$freedoom_version.zip"
mkdir -p "$cache"
if [[ "$(sha "$zip")" != "$freedoom_zip_sha" ]]; then
	curl -fsSL -o "$zip" \
		"https://github.com/freedoom/freedoom/releases/download/v$freedoom_version/freedoom-$freedoom_version.zip"
fi
if [[ "$(sha "$zip")" != "$freedoom_zip_sha" ]]; then
	echo "error: Freedoom archive does not match the pinned SHA-256" >&2
	exit 1
fi
mkdir -p "$engine"
for wad in freedoom1 freedoom2; do
	unzip -o -q -j "$zip" "*$wad.wad" -d "$cache"
	gzip -9 -n -c "$cache/$wad.wad" > "$engine/$wad.wad.gz"
done

# 3. The wasm engine. One build directory keeps index.js and index.wasm a
#    matched pair. -sDYNAMIC_EXECUTION=0 keeps 'unsafe-eval' out of the CSP.
emcmake cmake -S "$root" -B "$build" -DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_EXE_LINKER_FLAGS="-sDYNAMIC_EXECUTION=0"
cmake --build "$build" -j"$(nproc)"

# The preload manifest lives in index.js; index.data itself is raw contents.
if ! grep -aq "prboomx.wad" "$build/index.js"; then
	echo "error: prboomx.wad was not preloaded into index.data" >&2
	exit 1
fi
cp "$build/index.js" "$build/index.wasm" "$build/index.data" "$engine/"
echo "Engine written to $engine"

# 4. Optional release archive, laid out the way the app store wants it.
if [[ "${1:-}" == "--pack" ]]; then
	version="$(sed -n 's/.*<version>\(.*\)<\/version>.*/\1/p' "$root/nextcloud/appinfo/info.xml")"
	stage="$root/dist/dwasm"
	rm -rf "$root/dist"
	mkdir -p "$stage"
	cp -r "$root/nextcloud/." "$stage/"
	rm -rf "$stage/tests" "$stage/tools" "$stage/vendor"
	cp "$root/COPYING" "$stage/"
	tar -czf "$root/dist/dwasm-$version.tar.gz" -C "$root/dist" dwasm
	echo "Release archive: $root/dist/dwasm-$version.tar.gz"
fi